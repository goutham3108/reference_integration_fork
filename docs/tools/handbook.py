"""Generate local evidence appendices and the consolidated Markdown handbook."""

import argparse
import os
import re
import subprocess
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
PAGES = DOCS / "handbook"
ORDER = [
    "index", "overview", "architecture", "repository-tour", "workspace", "signals",
    "vehicle", "gateway", "serializer", "bridge", "remote", "score", "kuksa",
    "runtime", "platforms", "build-run-deploy", "configuration", "testing-ci",
    "fork-changes", "contributing-debugging", "glossary", "faq", "verification",
    "changed-files", "configuration-files", "environment-flags",
]
LINK = re.compile(r"\[([^\]\n]+)\]\(([^()\s]+)\)")


def git(*args: str) -> str:
    return subprocess.check_output(
        ["git", "--no-pager", *args], cwd=ROOT, text=True
    ).strip()


def cell(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ")


def write_appendices() -> None:
    base = git("merge-base", "origin/main", "HEAD")
    changes = git("diff", "--name-status", f"{base}...HEAD").splitlines()
    subjects: dict[str, str] = {}
    subject = ""
    for line in git("log", "--format=COMMIT %h %s", "--name-only", f"{base}..HEAD").splitlines():
        if line.startswith("COMMIT "):
            subject = line[7:]
        elif line:
            subjects.setdefault(line, subject)
    rows = []
    for change in changes:
        parts = change.split("\t")
        status, path = parts[0], parts[-1]
        old = f" (from `{parts[1]}`)" if len(parts) == 3 else ""
        location = f"[{path}](../../{path})" if (ROOT / path).exists() else f"`{path}` (removed)"
        reason = subjects.get(path, "No branch-only commit subject found")
        rows.append(f"| {status} | {location}{old} | {cell(reason)} | Unverified: individual design rationale; see commit subject and component analysis. |")
    (PAGES / "changed-files.md").write_text(
        "# Complete Branch File Changes\n\n"
        "This is the complete tracked change list from the locally available shared ancestor "
        f"`{base}` to HEAD `{git('rev-parse', '--short', 'HEAD')}`. "
        "Commit subjects are evidence of recorded intent, not proof of each file's design rationale; "
        "removed files have no current source link.\n\n"
        "Generated by [handbook.py](../tools/handbook.py), `write_appendices`; "
        "the main interpretation is in [Changes in this Fork](fork-changes.md).\n\n"
        "| Status | File | Latest branch commit touching destination | Reason confidence |\n"
        "| --- | --- | --- | --- |\n" + "\n".join(rows) +
        "\n\n## Related pages\n\n[Changes in this Fork](fork-changes.md) | [Repository Tour](repository-tour.md)\n"
    )
    tracked = git("ls-files").splitlines()
    config_names = {
        "BUILD", "BUILD.bazel", "MODULE.bazel", "MODULE.bazel.lock", "WORKSPACE",
        "Cargo.toml", "Cargo.lock", "Dockerfile", "Cross.toml", "known_good.json",
        "score_starter",
    }
    config_extensions = {".json", ".yaml", ".yml", ".toml", ".bazel", ".bazelrc", ".env", ".fbs", ".proto", ".bzl", ".cmake", ".ini", ".cfg"}
    configs = [
        path for path in tracked
        if Path(path).name in config_names
        or Path(path).suffix in config_extensions
        or Path(path).name.startswith((".bazel", ".clang", ".gitignore", ".gitattributes", ".shellcheck", ".yamlfmt"))
        or Path(path).name.startswith("requirements")
        or (Path(path).name.startswith("Dockerfile"))
    ]
    config_rows = [
        f"| [{path}](../../{path}) | `{Path(path).suffix or Path(path).name}` | "
        f"{'Vendored module' if path.split('/')[0] in {'baselibs', 'communication', 'inc_someip_gateway', 'kuksa-databroker'} else 'Integration workspace'} |"
        for path in configs if (ROOT / path).exists()
    ]
    (PAGES / "configuration-files.md").write_text(
        "# Configuration File Inventory\n\n"
        "This inventory enumerates tracked build manifests, lockfiles, JSON data/configuration, "
        "schemas, workflow files and recognized tool settings. Inclusion does not mean a file "
        "is loaded by the demo: test fixtures, vendored examples and schemas are deliberately retained "
        "so they are not mistaken for active configuration.\n\n"
        "Generated by [handbook.py](../tools/handbook.py), `write_appendices`; "
        "classification is by path/name, not execution. Unverified: extensionless or dynamically "
        "named configuration outside the enumerated filename rules.\n\n"
        "| Path | Format/name | Ownership boundary |\n| --- | --- | --- |\n" +
        "\n".join(config_rows) +
        "\n\n## Related pages\n\n[Configuration Reference](configuration.md) | [Repository Tour](repository-tour.md)\n"
    )
    patterns = [
        ("Environment", re.compile(r'(?:getenv|var_os|std::env::var|env::var|option_env!|env!)\s*\(\s*"([A-Z][A-Z0-9_]*)"')),
        ("Environment", re.compile(r'(?:environ\.get|os\.getenv)\s*\(\s*[\'"]([A-Z][A-Z0-9_]*)[\'"]')),
        ("Environment", re.compile(r'environ\s*\[\s*[\'"]([A-Z][A-Z0-9_]*)[\'"]\s*\]')),
        ("Environment", re.compile(r'\$\{([A-Z][A-Z0-9_]*)(?=[:}%+\-/])')),
        ("Environment", re.compile(r'^\s*(?:export\s+|ENV\s+)([A-Z][A-Z0-9_]*)[=\s]')),
        ("Environment", re.compile(r'\.env\(\s*"([A-Z][A-Z0-9_]*)"')),
        ("Flag", re.compile(r'\.long\(\s*"([^"]+)"')),
        ("Flag", re.compile(r'add_argument\(\s*[\'"](--?[^\'"]+)[\'"]')),
        ("Flag", re.compile(r'^\s*\{\s*"([a-z][a-z_-]+)",\s*(?:no_argument|required_argument|optional_argument)')),
        ("Flag", re.compile(r'^\s*"(--[a-z][a-z_-]+)"\s*=>')),
    ]
    findings: list[tuple[str, str, str, int]] = []
    extensions = {".py", ".rs", ".cc", ".cpp", ".h", ".hpp", ".sh", ".bazel", ".bzl", ".yml", ".yaml"}
    for path in tracked:
        source = ROOT / path
        if not source.is_file() or source.is_symlink() or source.stat().st_size > 1_000_000:
            continue
        if source.suffix not in extensions and source.name not in {"Dockerfile", "BUILD", "score_starter"}:
            continue
        for number, line in enumerate(source.read_text(errors="replace").splitlines(), 1):
            for kind, pattern in patterns:
                for match in pattern.finditer(line):
                    findings.append((kind, match[1], path, number))
    finding_rows = [
        f"| {kind} | `{cell(name)}` | [{path}:{number}](../../{path}#L{number}) | Unverified here; see source and operational reference. |"
        for kind, name, path, number in sorted(set(findings))
    ]
    (PAGES / "environment-flags.md").write_text(
        "# Static Environment and Flag Inventory\n\n"
        "This is a repository-wide index of literal environment-variable and CLI declaration "
        "references, including vendored examples, build-time variables and tests. "
        "It is not a claim that every reference is a supported demo setting.\n\n"
        "Generated by [handbook.py](../tools/handbook.py), `write_appendices`. "
        "Unverified: computed names, multiline declarations not matched by the scanner, flags "
        "embedded in patch files, library-defined flags, and implicit third-party settings; "
        "the [operational reference](configuration.md) separately covers the committed runtime patch.\n\n"
        "| Kind | Literal name | Evidence | Default/activation |\n| --- | --- | --- | --- |\n" +
        "\n".join(finding_rows) +
        "\n\n## Related pages\n\n[Configuration Reference](configuration.md) | [Verification](verification.md)\n"
    )


def consolidate() -> None:
    titles = {
        name: re.search(r"^# (.+)$", (PAGES / f"{name}.md").read_text(), re.M)[1]
        for name in ORDER
    }
    sections = [
        "# S-CORE SDV Integration: Definitive Local Handbook\n\n"
        "This handbook documents the local `sdv-hackathon` checkout at `0842972`. "
        "It separates code-observed behavior, earlier fork inheritance, branch changes, "
        "and explicitly unverified runtime behavior. The same chapters form the MkDocs Material site.\n\n"
        "Preview setup and limitations are in [Build, Run and Deploy](#chapter-build-run-deploy). "
        "Regenerate this document with `python3 -B docs/tools/handbook.py generate`; "
        "edit chapter sources under `docs/handbook/`, not this generated copy.\n\n"
        "## Contents\n\n" +
        "\n".join(f"- [{titles[name]}](#chapter-{name})" for name in ORDER)
    ]
    for name in ORDER:
        text = (PAGES / f"{name}.md").read_text()

        def rewrite(match):
            label, target = match.groups()
            parsed = urlsplit(target)
            if parsed.scheme or not parsed.path:
                return match.group(0)
            target_page = Path(parsed.path).stem
            if parsed.path.endswith(".md") and target_page in ORDER:
                if parsed.fragment:
                    return f"[{label}](handbook/{target})"
                return f"[{label}](#chapter-{target_page})"
            resolved = (PAGES / unquote(parsed.path)).resolve()
            relative = Path(os.path.relpath(resolved, DOCS)).as_posix()
            fragment = f"#{parsed.fragment}" if parsed.fragment else ""
            return f"[{label}]({relative}{fragment})"

        text = LINK.sub(rewrite, text)
        text = re.sub(r"^(#{1,5}) ", r"#\1 ", text, flags=re.M)
        sections.append(f'<a id="chapter-{name}"></a>\n\n{text}')
    (DOCS / "document.md").write_text("\n\n---\n\n".join(sections) + "\n")


def validate() -> None:
    errors = []
    for source in [DOCS / "document.md", *PAGES.glob("*.md")]:
        for _, target in LINK.findall(source.read_text()):
            parsed = urlsplit(target)
            if not parsed.path and parsed.fragment.startswith("chapter-"):
                if f'id="{parsed.fragment}"' not in source.read_text():
                    errors.append(f"{source.relative_to(ROOT)}: missing anchor {target}")
            if parsed.scheme or not parsed.path or parsed.path.startswith("/"):
                continue
            resolved = (source.parent / unquote(parsed.path)).resolve()
            if not resolved.is_relative_to(ROOT) or not resolved.exists():
                errors.append(f"{source.relative_to(ROOT)}: missing/outside link {target}")
            elif re.fullmatch(r"L\d+", parsed.fragment) and resolved.is_file():
                line = int(parsed.fragment[1:])
                if line < 1 or line > len(resolved.read_text(errors="replace").splitlines()):
                    errors.append(f"{source.relative_to(ROOT)}: invalid source line {target}")
    if errors:
        raise SystemExit("\n".join(errors))
    print(f"Validated repository-relative links in {len(list(PAGES.glob('*.md'))) + 1} Markdown files.")


class SitePage(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.ids: set[str] = set()
        self.targets: list[str] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = dict(attrs)
        if identifier := attributes.get("id"):
            self.ids.add(identifier)
        for attribute in ("href", "src"):
            if target := attributes.get(attribute):
                self.targets.append(target)


def validate_site() -> None:
    site = DOCS / "_handbook_site"
    if not (site / "index.html").is_file():
        raise SystemExit("Build the handbook site before running the site check.")
    pages = {}
    for path in site.rglob("*.html"):
        page = SitePage()
        page.feed(path.read_text())
        pages[path.resolve()] = page
    errors = []
    checked = 0
    for source, page in pages.items():
        for target in page.targets:
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc:
                continue
            if not parsed.path:
                destination = source
            elif parsed.path.startswith("/"):
                destination = (site / unquote(parsed.path.lstrip("/"))).resolve()
            else:
                destination = (source.parent / unquote(parsed.path)).resolve()
            if destination.is_dir():
                destination /= "index.html"
            checked += 1
            if not destination.is_relative_to(site.resolve()) or not destination.exists():
                errors.append(f"{source.name}: missing asset/link {target}")
            elif destination in pages and parsed.fragment:
                if unquote(parsed.fragment) not in pages[destination].ids:
                    errors.append(f"{source.name}: missing anchor {target}")
    if errors:
        raise SystemExit("\n".join(errors))
    print(f"Validated {checked} local HTML links/assets/anchors across {len(pages)} rendered pages.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["generate", "check", "site"])
    args = parser.parse_args()
    if args.command == "site":
        validate_site()
        return
    if args.command == "generate":
        write_appendices()
        consolidate()
    validate()


if __name__ == "__main__":
    main()
